def cmd_preview(args):
    if not args:
        print("usage: build.py preview <slug>")
        return 2
    slug = args[0]
    posts = load_posts()
    legacy = load_legacy()
    post = next((p for p in posts if p.slug == slug), None)
    if post is None:
        print(f"no post named {slug} in drafts/, posts/ or held/")
        return 1
    errs = []
    page, info = render_post(post, posts + legacy, errs)
    out = os.path.join(HERE, "preview", slug + ".html")
    # previews use root-relative assets; rewrite to absolute so the file opens standalone
    page = page.replace('href="/assets/', f'href="{CONFIG["site_url"]}/assets/').replace('src="/assets/', f'src="{CONFIG["site_url"]}/assets/')
    write_if_changed(out, page)
    v_errs, v_warns = validate_post(post, posts + legacy, {p.slug for p in posts + legacy if p.is_live})
    for w in v_warns:
        print("WARN  " + w)
    for e in v_errs:
        print("FAIL  " + e)
    print(f"{out}  ({info['words']} words, {len(info['h2s'])} H2, {info['faq_n']} FAQ)")
    return 0


def cmd_publish(args):
    now = datetime.now(TZ)
    dry = "--dry-run" in args
    if "--now" in args:
        now = datetime.fromisoformat(args[args.index("--now") + 1])
        if now.tzinfo is None:
            now = now.replace(tzinfo=TZ)
    posts = load_posts()
    legacy = load_legacy()
    everything = posts + legacy
    approved = [p for p in posts if p.state_dir == "posts" and p.meta.get("status") == "approved"]
    due = [p for p in approved if p.when <= now]
    live_slugs = {p.slug for p in everything if p.is_live}
    # validate everything that will be live after this run
    failed = False
    for p in due:
        errs, _ = validate_post(p, everything, live_slugs | {d.slug for d in due})
        for e in errs:
            print(f"FAIL  {p.slug}: {e}")
            failed = True
    if failed:
        print("publish aborted: validation failed")
        return 1
    newly = [p for p in due if not p.is_live]
    changed = []
    if not dry:
        # render every due post (re-renders refresh Related guides on older posts)
        for p in due:
            page, _ = render_post(p, everything)
            if write_if_changed(p.rendered_path, page):
                changed.append(f"blog/{p.slug}/index.html")
        # prune generated dirs whose .md is gone
        keep = {p.slug for p in due} | {l.slug for l in legacy}
        blog_dir = os.path.join(ROOT, "blog")
        for name in os.listdir(blog_dir):
            d = os.path.join(blog_dir, name)
            idx = os.path.join(d, "index.html")
            if os.path.isdir(d) and name not in keep and os.path.exists(idx) and MARKER in read(idx)[:400]:
                shutil.rmtree(d)
                changed.append(f"blog/{name}/ (removed)")
        changed += write_site_files(legacy + due)
    print(f"now={now.isoformat()} approved={len(approved)} due={len(due)} new={len(newly)}")
    for p in newly:
        print(f"PUBLISHED {p.slug} -> {p.url}")
    if changed:
        print("changed: " + ", ".join(changed))
    else:
        print("nothing due")
    return 0


def cmd_status(args):
    now = datetime.now(TZ)
    rows = []
    for p in load_posts():
        st = p.meta.get("status", "?")
        if p.state_dir == "held":
            state = "held"
        elif p.is_live:
            state = "LIVE"
        elif st == "approved" and p.when <= now:
            state = "DUE (approved, not yet published)"
        elif st == "approved":
            state = "queued"
        else:
            state = "draft"
        rows.append((p.sort_key, p.slug, p.meta.get("pillar", "?"), state))
    for l in load_legacy():
        rows.append((l.sort_key, l.slug, l.meta.get("pillar", "?"), "LIVE (legacy)"))
    rows.sort()
    for k, slug, pillar, state in rows:
        print(f"{k}  {pillar:3}  {slug:45} {state}")
    return 0


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    cmd, args = argv[1], argv[2:]
    if cmd == "validate":
        return cmd_validate(args)
    if cmd == "preview":
        return cmd_preview(args)
    if cmd == "publish":
        return cmd_publish(args)
    if cmd == "status":
        return cmd_status(args)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
